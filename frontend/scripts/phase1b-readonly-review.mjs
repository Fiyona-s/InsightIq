import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const mutations=[];page.on('request',r=>{if(r.url().includes('/api/')&&!['GET','HEAD','OPTIONS'].includes(r.method()))mutations.push({method:r.method(),path:new URL(r.url()).pathname});});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:8080');
await expect(page.getByRole('heading',{name:'Data workspace.'})).toBeVisible();
await expect(page.getByRole('button',{name:'Active',exact:true})).toHaveAttribute('aria-pressed','true');
await expect(page.getByLabel('Select all visible datasets')).toBeEnabled();
await page.getByRole('button',{name:'Archived',exact:true}).click();
await expect(page.getByText('No datasets in this view.',{exact:true})).toBeVisible();
await page.getByRole('button',{name:'Active',exact:true}).click();
const sampleBadges=await page.locator('.dataset-panel .sample-badge').count();
await page.getByRole('button',{name:'Dashboards',exact:true}).click();
await expect(page.locator('.result-kpi strong')).toHaveText('₹83,79,680.76');
await expect(page.getByRole('button',{name:'Convert Currency',exact:true}).first()).toBeVisible();
await expect(page.getByText('Local workspace',{exact:true})).toHaveCount(1);
expect(mutations).toEqual([]);expect(errors).toEqual([]);
const report={url:'http://localhost:8080',datasetFilters:true,emptyArchivedView:true,sampleBadgesVisible:sampleBadges,savedKPI:'₹83,79,680.76',conversionButtonVisible:true,apiMutations:mutations,browserErrors:errors};
fs.writeFileSync('../docs/phase1b/live-readonly-review.json',JSON.stringify(report,null,2));console.log(JSON.stringify(report));await browser.close();
